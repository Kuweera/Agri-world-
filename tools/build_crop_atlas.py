"""Builds assets/textures/crops.png and scripts/crop_atlas.gd from 10 plant pictures
(maize_1..5.png and bean_1..5.png: transparent background, whole plant, side view).
Usage (from the repo root): python3 tools/build_crop_atlas.py /path/to/folder_with_the_10_pngs
Each plant is cropped to its outline, scaled into a 512 px cell (bottom aligned) and its colour is
bled into the transparent area so mip-maps have no dark halo. crop_atlas.gd records, per cell,
the UV rectangle and the width/height ratio so the game can size each card correctly."""
import sys, os
import numpy as np
from PIL import Image, ImageFilter

SRC = sys.argv[1] if len(sys.argv) > 1 else "."
CELL = 512
COLS, ROWS = 4, 3
PAD = 3
names = [f"maize_{i}.png" for i in range(1, 6)] + [f"bean_{i}.png" for i in range(1, 6)]
# trim_bottom: fraction of the outline height cut off at the bottom (bean_1 comes with roots)
trim_bottom = {"bean_1.png": 0.0}
root_cut = {"bean_1.png": 1500}   # keep rows above this y in the 2048 picture (drops the roots)

def bleed(rgba):
    a = rgba[..., 3:4].astype(np.float32) / 255.0
    rgb = rgba[..., :3].astype(np.float32)
    pre = Image.fromarray((rgb * a).astype(np.uint8))
    al = Image.fromarray((a[..., 0] * 255).astype(np.uint8))
    out = rgb.copy()
    filled = a[..., 0] > 0.98
    for r in (6, 18, 48):
        p = np.asarray(pre.filter(ImageFilter.GaussianBlur(r)), dtype=np.float32)
        w = np.asarray(al.filter(ImageFilter.GaussianBlur(r)), dtype=np.float32)[..., None] / 255.0
        est = p / np.maximum(w, 1e-3)
        use = (~filled)[..., None] & (w > 0.02)
        out = np.where(use & (np.abs(out - rgb).sum(-1, keepdims=True) == 0), est, out) if False else np.where(use, est, out)
    out = np.where(filled[..., None], rgb, out)
    return np.dstack([np.clip(out, 0, 255), rgba[..., 3]]).astype(np.uint8)

atlas = Image.new("RGBA", (COLS * CELL, ROWS * CELL), (0, 0, 0, 0))
rects, aspects = [], []
for i, n in enumerate(names):
    im = Image.open(os.path.join(SRC, n)).convert("RGBA")
    if n in root_cut:
        arr = np.asarray(im).copy()
        arr[root_cut[n]:, :, 3] = 0
        im = Image.fromarray(arr)
    bbox = im.getchannel("A").point(lambda v: 255 if v > 24 else 0).getbbox()
    im = im.crop(bbox)
    w, h = im.size
    s = min((CELL - 2 * PAD) / w, (CELL - 2 * PAD) / h)
    nw, nh = max(1, round(w * s)), max(1, round(h * s))
    im = im.resize((nw, nh), Image.LANCZOS)
    a = bleed(np.asarray(im))
    im = Image.fromarray(a, "RGBA")
    cx, cy = (i % COLS) * CELL, (i // COLS) * CELL
    ox = cx + (CELL - nw) // 2
    oy = cy + CELL - PAD - nh
    # fill the whole cell with its edge colour (alpha 0) so no black leaks in when filtering
    avg = tuple(int(v) for v in np.asarray(im)[..., :3].reshape(-1, 3).mean(0))
    atlas.paste(Image.new("RGBA", (CELL, CELL), avg + (0,)), (cx, cy))
    atlas.paste(im, (ox, oy))
    rects.append((ox / (COLS * CELL), oy / (ROWS * CELL), nw / (COLS * CELL), nh / (ROWS * CELL)))
    aspects.append(nw / nh)
atlas.save("assets/textures/crops.png", optimize=True)

with open("scripts/crop_atlas.gd", "w") as f:
    f.write("extends RefCounted\n# Generated by tools/build_crop_atlas.py. Do not edit by hand.\n")
    f.write("# Cells 0-4: maize stages 1-5, cells 5-9: bean stages 1-5.\n")
    f.write("const RECTS := [\n")
    for r in rects:
        f.write("\tRect2(%.6f, %.6f, %.6f, %.6f),\n" % r)
    f.write("]\n# width / height of each plant picture\nconst ASPECT := [\n")
    for a in aspects:
        f.write("\t%.4f,\n" % a)
    f.write("]\n")
print("ok", [round(a, 2) for a in aspects])
